-- ─────────────────────────────────────────────────────────────
-- 6. Realtime — let the frontend subscribe to changes
-- ─────────────────────────────────────────────────────────────
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'news'
  ) then
    alter publication supabase_realtime add table public.news;
  end if;
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'posters'
  ) then
    alter publication supabase_realtime add table public.posters;
  end if;
end $$;


