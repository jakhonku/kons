-- ─────────────────────────────────────────────────────────────
-- 1. Helper function: is the current request the admin?
--    >>>>> REPLACE 'admin@konservatoriya.uz' WITH YOUR EMAIL <<<<<
-- ─────────────────────────────────────────────────────────────
create or replace function public.is_admin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select coalesce(
    lower(auth.jwt() ->> 'email') = lower('admin@konservatoriya.uz'),
    false
  )
$$;

-- Lock down who can call this helper
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;


-- ─────────────────────────────────────────────────────────────
-- 2. NEWS table
-- ─────────────────────────────────────────────────────────────
create table if not exists public.news (
  id          bigint generated by default as identity primary key,
  title       text not null,
  category    text not null default 'Voqealar',
  date        date,
  excerpt     text,
  body        text,
  image       text,
  zoom_link   text,
  featured    boolean not null default false,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists news_created_at_idx on public.news (created_at desc);
create index if not exists news_category_idx on public.news (category);

alter table public.news enable row level security;

drop policy if exists "news_public_read"  on public.news;
drop policy if exists "news_admin_insert" on public.news;
drop policy if exists "news_admin_update" on public.news;
drop policy if exists "news_admin_delete" on public.news;

create policy "news_public_read"
  on public.news for select
  using (true);

create policy "news_admin_insert"
  on public.news for insert
  to authenticated
  with check (public.is_admin());

create policy "news_admin_update"
  on public.news for update
  to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "news_admin_delete"
  on public.news for delete
  to authenticated
  using (public.is_admin());


